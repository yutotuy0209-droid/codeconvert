#!/usr/bin/env python3
"""Export code relationship maps into presentation-ready assets.

Inputs are generated by project_mapper.py:
- repo_map.json
- file_relationships.json

Outputs:
- PowerPoint .pptx with native rectangles/connectors
- SVG frame storyboard for motion explanation
- Optional GIF when Pillow is available

This module intentionally keeps the core export path standard-library only.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import html
import json
import math
from pathlib import Path
import zipfile


@dataclass(frozen=True)
class NodeSummary:
    path: str
    function_count: int
    functions: tuple[str, ...]


@dataclass(frozen=True)
class RelationSummary:
    source: str
    target: str
    relation: str
    labels: tuple[str, ...]


@dataclass(frozen=True)
class ProjectSummary:
    nodes: dict[str, NodeSummary]
    relations: tuple[RelationSummary, ...]
    ambiguities: tuple[dict, ...]


def _esc(text: object) -> str:
    return html.escape(str(text), quote=True)


def _short(text: str, limit: int = 46) -> str:
    text = str(text)
    return text if len(text) <= limit else "…" + text[-(limit - 1):]


def load_project_summary(map_dir: Path) -> ProjectSummary:
    map_dir = Path(map_dir)
    repo_map_path = map_dir / "repo_map.json"
    relations_path = map_dir / "file_relationships.json"
    if not repo_map_path.exists():
        raise FileNotFoundError(f"missing {repo_map_path}")
    if not relations_path.exists():
        raise FileNotFoundError(f"missing {relations_path}")

    repo_map = json.loads(repo_map_path.read_text(encoding="utf-8"))
    relation_data = json.loads(relations_path.read_text(encoding="utf-8"))

    nodes: dict[str, NodeSummary] = {}
    for path, funcs in sorted(repo_map.items()):
        names: list[str] = []
        for func in funcs:
            names.append(str(func.get("name") or func.get("qualified_name") or "function"))
        nodes[path] = NodeSummary(path=path, function_count=len(funcs), functions=tuple(names[:5]))

    relations = tuple(
        RelationSummary(
            source=str(item.get("source", "")),
            target=str(item.get("target", "")),
            relation=str(item.get("relation", "edge")),
            labels=tuple(str(v) for v in item.get("labels", [])[:6]),
        )
        for item in relation_data.get("relations", [])
        if item.get("source") and item.get("target")
    )
    ambiguities = tuple(relation_data.get("ambiguities", []))
    return ProjectSummary(nodes=nodes, relations=relations, ambiguities=ambiguities)


