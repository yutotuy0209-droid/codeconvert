def _frame_svg(summary: ProjectSummary, active_index: int) -> str:
    nodes = sorted(summary.nodes)
    positions = _positions(nodes)
    width, height = 1280, 720
    rels = list(summary.relations)
    active = rels[active_index] if 0 <= active_index < len(rels) else None
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="#F8FAFC"/>',
        '<text x="54" y="50" font-family="Yu Gothic, Segoe UI" font-size="28" font-weight="700" fill="#0F172A">Code relationship motion storyboard</text>',
    ]

    def sx(inch: float) -> int:
        return int(inch * 96)

    for i, rel in enumerate(rels[:24]):
        if rel.source not in positions or rel.target not in positions:
            continue
        x1, y1 = positions[rel.source]
        x2, y2 = positions[rel.target]
        color = "#DC2626" if i == active_index else ("#2563EB" if rel.relation == "call" else "#64748B")
        stroke = 5 if i == active_index else 2
        parts.append(
            f'<line x1="{sx(x1+1.38)}" y1="{sx(y1+0.45)}" x2="{sx(x2+1.38)}" y2="{sx(y2+0.45)}" stroke="{color}" stroke-width="{stroke}" opacity="0.85"/>'
        )
    for node in nodes[:15]:
        x, y = positions[node]
        fill = "#FEF2F2" if active and node in (active.source, active.target) else "#FFFFFF"
        line = "#DC2626" if active and node in (active.source, active.target) else "#475569"
        ns = summary.nodes[node]
        parts.append(f'<rect x="{sx(x)}" y="{sx(y)}" width="265" height="82" rx="12" fill="{fill}" stroke="{line}" stroke-width="2"/>')
        parts.append(f'<text x="{sx(x)+14}" y="{sx(y)+28}" font-family="Yu Gothic, Segoe UI" font-size="14" font-weight="700" fill="#0F172A">{_esc(_short(node, 31))}</text>')
        parts.append(f'<text x="{sx(x)+14}" y="{sx(y)+52}" font-family="Yu Gothic, Segoe UI" font-size="12" fill="#475569">{ns.function_count} functions</text>')
    if active:
        label = active.relation.upper()
        if active.labels:
            label += " / " + ", ".join(active.labels[:3])
        parts.append(f'<text x="54" y="680" font-family="Yu Gothic, Segoe UI" font-size="22" font-weight="700" fill="#DC2626">Step {active_index+1}: {_esc(active.source)} → {_esc(active.target)} ({_esc(label)})</text>')
    parts.append("</svg>")
    return "\n".join(parts)


def _motion_html(frame_count: int) -> str:
    options = "\n".join(
        f'<button onclick="show({i})">{i+1}</button>' for i in range(frame_count)
    )
    return f'''<!doctype html>
<html lang="ja"><head><meta charset="utf-8"><title>Code relationship motion storyboard</title>
<style>body{{font-family:system-ui,"Yu Gothic",sans-serif;background:#0F172A;color:#F8FAFC;margin:0;padding:24px}}button{{margin:3px;padding:6px 10px;border:0;border-radius:6px;background:#2563EB;color:white}}iframe{{width:100%;height:76vh;border:1px solid #334155;background:white;border-radius:10px}}</style></head>
<body><h1>Code relationship motion storyboard</h1><p>GIFの代替として、関係を1ステップずつ確認するHTMLです。Pillowがある環境ではGIFも生成します。</p><div>{options}</div><iframe id="frame" src="frames/frame_001.svg"></iframe>
<script>function show(i){{document.getElementById('frame').src='frames/frame_'+String(i+1).padStart(3,'0')+'.svg';}}</script></body></html>'''


def _try_write_gif(summary: ProjectSummary, out_dir: Path) -> Path | None:
    try:
        from PIL import Image, ImageDraw, ImageFont  # type: ignore
    except Exception:
        return None
    frames = []
    nodes = sorted(summary.nodes)[:12]
    positions = _positions(nodes)
    rels = list(summary.relations)[:24]
    w, h = 960, 540
    for idx in range(max(1, len(rels))):
        image = Image.new("RGB", (w, h), "#F8FAFC")
        draw = ImageDraw.Draw(image)
        draw.text((32, 26), "Code relationship motion", fill="#0F172A")
        active = rels[idx] if idx < len(rels) else None
        def px(v: float) -> int:
            return int(v * 72)
        for i, rel in enumerate(rels):
            if rel.source in positions and rel.target in positions:
                x1, y1 = positions[rel.source]
                x2, y2 = positions[rel.target]
                color = "#DC2626" if i == idx else "#2563EB"
                draw.line((px(x1+1.3), px(y1+0.42), px(x2+1.3), px(y2+0.42)), fill=color, width=4 if i == idx else 2)
        for node in nodes:
            x, y = positions[node]
            fill = "#FEF2F2" if active and node in (active.source, active.target) else "#FFFFFF"
            outline = "#DC2626" if active and node in (active.source, active.target) else "#475569"
            draw.rounded_rectangle((px(x), px(y), px(x)+198, px(y)+62), radius=10, fill=fill, outline=outline, width=2)
            draw.text((px(x)+8, px(y)+12), _short(node, 24), fill="#0F172A")
        frames.append(image)
    out = out_dir / "relationship_motion.gif"
    frames[0].save(out, save_all=True, append_images=frames[1:], duration=900, loop=0)
    return out


def export_motion_storyboard(map_dir: Path, out_dir: Path) -> dict[str, str]:
    summary = load_project_summary(map_dir)
    out_dir = Path(out_dir)
    frames_dir = out_dir / "frames"
    frames_dir.mkdir(parents=True, exist_ok=True)
    frame_count = max(1, len(summary.relations))
    for i in range(frame_count):
        (frames_dir / f"frame_{i+1:03d}.svg").write_text(_frame_svg(summary, i), encoding="utf-8")
    (out_dir / "motion_storyboard.html").write_text(_motion_html(frame_count), encoding="utf-8")
    gif_path = _try_write_gif(summary, out_dir)
    return {
        "format": "gif+html" if gif_path else "html+svg-frames",
        "html": str(out_dir / "motion_storyboard.html"),
        "gif": str(gif_path) if gif_path else "",
    }


def export_pack(map_dir: Path, out_dir: Path) -> dict[str, str]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    pptx = export_pptx(map_dir, out_dir / "relationship_deck.pptx")
    motion = export_motion_storyboard(map_dir, out_dir / "motion")
    return {"pptx": str(pptx), **motion}


def main() -> int:
    parser = argparse.ArgumentParser(description="Export project relationship map to presentation assets.")
    parser.add_argument("map_dir", type=Path, help="Directory containing repo_map.json and file_relationships.json")
    parser.add_argument("--out", type=Path, default=Path("output/presentation_pack"), help="Output directory")
    parser.add_argument("--pptx", action="store_true", help="Export only PPTX")
    parser.add_argument("--motion", action="store_true", help="Export only motion storyboard / optional GIF")
    args = parser.parse_args()

    if args.pptx and not args.motion:
        print(export_pptx(args.map_dir, args.out / "relationship_deck.pptx"))
    elif args.motion and not args.pptx:
        print(json.dumps(export_motion_storyboard(args.map_dir, args.out / "motion"), ensure_ascii=False, indent=2))
    else:
        print(json.dumps(export_pack(args.map_dir, args.out), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
