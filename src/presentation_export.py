EMU_PER_INCH = 914400


def _emu(inch: float) -> int:
    return int(round(inch * EMU_PER_INCH))


def _ppt_text(x: float, y: float, w: float, h: float, text: str, *, size: int = 1800, bold: bool = False) -> str:
    b = '<a:b/>' if bold else ''
    return f'''
<p:sp>
  <p:nvSpPr><p:cNvPr id="{_shape_id()}" name="TextBox"/><p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr>
  <p:spPr><a:xfrm><a:off x="{_emu(x)}" y="{_emu(y)}"/><a:ext cx="{_emu(w)}" cy="{_emu(h)}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/><a:ln><a:noFill/></a:ln></p:spPr>
  <p:txBody><a:bodyPr wrap="square"/><a:lstStyle/><a:p><a:r><a:rPr lang="ja-JP" sz="{size}">{b}</a:rPr><a:t>{_esc(text)}</a:t></a:r></a:p></p:txBody>
</p:sp>'''


_next_shape_id = 100


def _shape_id() -> int:
    global _next_shape_id
    _next_shape_id += 1
    return _next_shape_id


def _ppt_rect(x: float, y: float, w: float, h: float, title: str, body: str, fill: str = "FFFFFF", line: str = "475569") -> str:
    return f'''
<p:sp>
  <p:nvSpPr><p:cNvPr id="{_shape_id()}" name="{_esc(title)}"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>
  <p:spPr>
    <a:xfrm><a:off x="{_emu(x)}" y="{_emu(y)}"/><a:ext cx="{_emu(w)}" cy="{_emu(h)}"/></a:xfrm>
    <a:prstGeom prst="roundRect"><a:avLst/></a:prstGeom>
    <a:solidFill><a:srgbClr val="{fill}"/></a:solidFill>
    <a:ln w="16000"><a:solidFill><a:srgbClr val="{line}"/></a:solidFill></a:ln>
  </p:spPr>
  <p:txBody>
    <a:bodyPr wrap="square" lIns="90000" tIns="65000" rIns="90000" bIns="65000"/>
    <a:lstStyle/>
    <a:p><a:r><a:rPr lang="ja-JP" sz="1050"><a:b/></a:rPr><a:t>{_esc(_short(title, 38))}</a:t></a:r></a:p>
    <a:p><a:r><a:rPr lang="ja-JP" sz="850"/><a:t>{_esc(body)}</a:t></a:r></a:p>
  </p:txBody>
</p:sp>'''


def _ppt_line(x1: float, y1: float, x2: float, y2: float, label: str, *, color: str = "2563EB", dashed: bool = False) -> str:
    dash = '<a:prstDash val="dash"/>' if dashed else ''
    # Straight connector, then label as separate text box near middle.
    label_xml = _ppt_text((x1 + x2) / 2 - 0.65, (y1 + y2) / 2 - 0.16, 1.3, 0.28, _short(label, 18), size=700, bold=True)
    return f'''
<p:cxnSp>
  <p:nvCxnSpPr><p:cNvPr id="{_shape_id()}" name="Connector"/><p:cNvCxnSpPr/><p:nvPr/></p:nvCxnSpPr>
  <p:spPr>
    <a:xfrm><a:off x="{_emu(min(x1, x2))}" y="{_emu(min(y1, y2))}"/><a:ext cx="{_emu(abs(x2 - x1) or 0.01)}" cy="{_emu(abs(y2 - y1) or 0.01)}"/></a:xfrm>
    <a:prstGeom prst="line"><a:avLst/></a:prstGeom>
    <a:ln w="19000">{dash}<a:solidFill><a:srgbClr val="{color}"/></a:solidFill><a:tailEnd type="triangle"/></a:ln>
  </p:spPr>
</p:cxnSp>
{label_xml}'''


def _positions(nodes: list[str]) -> dict[str, tuple[float, float]]:
    cols = 3
    x0, y0 = 0.65, 1.35
    gap_x, gap_y = 3.45, 1.45
    return {name: (x0 + (i % cols) * gap_x, y0 + (i // cols) * gap_y) for i, name in enumerate(nodes)}


def _slide_xml(shapes: str) -> str:
    return f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">
  <p:cSld><p:spTree>
    <p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
    <p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>
    {shapes}
  </p:spTree></p:cSld><p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr>
</p:sld>'''


def _presentation_xml(slide_count: int) -> str:
    ids = "\n".join(
        f'<p:sldId id="{256+i}" r:id="rId{i+1}"/>' for i in range(slide_count)
    )
    return f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:presentation xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">
  <p:sldSz cx="12192000" cy="6858000" type="wide"/>
  <p:notesSz cx="6858000" cy="9144000"/>
  <p:sldIdLst>{ids}</p:sldIdLst>
</p:presentation>'''


def _presentation_rels(slide_count: int) -> str:
    rels = "\n".join(
        f'<Relationship Id="rId{i+1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide{i+1}.xml"/>'
        for i in range(slide_count)
    )
    return f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">{rels}</Relationships>'''


def _content_types(slide_count: int) -> str:
    overrides = "\n".join(
        f'<Override PartName="/ppt/slides/slide{i+1}.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>'
        for i in range(slide_count)
    )
    return f'''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>
  {overrides}
</Types>'''


def _root_rels() -> str:
    return '''<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/>
</Relationships>'''


def _deck_slides(summary: ProjectSummary) -> list[str]:
    global _next_shape_id
    _next_shape_id = 100
    nodes = list(sorted(summary.nodes))
    rels = list(summary.relations)

    slide1 = _slide_xml(
        _ppt_text(0.7, 0.65, 11.0, 0.6, "Code Relationship Map", size=2800, bold=True)
        + _ppt_text(0.78, 1.35, 10.7, 0.45, "Multiple files/folders → JSON → SVG/Mermaid/PPTX/GIF assets", size=1350)
        + _ppt_rect(0.9, 2.2, 3.1, 1.0, "Input", "Folders / .py / .cpp / .hpp / .m", "EFF6FF", "2563EB")
        + _ppt_rect(4.55, 2.2, 3.1, 1.0, "Analysis", "import / include / call / ambiguity", "F0FDF4", "16A34A")
        + _ppt_rect(8.2, 2.2, 3.1, 1.0, "Output", "SVG / Mermaid / PPTX / GIF storyboard", "FFF7ED", "EA580C")
        + _ppt_line(4.0, 2.7, 4.55, 2.7, "")
        + _ppt_line(7.65, 2.7, 8.2, 2.7, "")
        + _ppt_text(0.9, 4.25, 10.8, 0.7, f"Nodes: {len(nodes)}   Relations: {len(rels)}   Ambiguities: {len(summary.ambiguities)}", size=1200)
    )

    _next_shape_id = 300
    positions = _positions(nodes)
    diagram_shapes = _ppt_text(0.55, 0.35, 11.2, 0.42, "File relationship diagram", size=2100, bold=True)
    for rel in rels[:18]:
        if rel.source in positions and rel.target in positions:
            sx, sy = positions[rel.source]
            tx, ty = positions[rel.target]
            color = "2563EB" if rel.relation == "call" else "64748B"
            dashed = rel.relation not in ("call", "include")
            label = rel.relation.upper()
            if rel.labels:
                label += ": " + ", ".join(rel.labels[:2])
            diagram_shapes += _ppt_line(sx + 1.4, sy + 0.45, tx + 1.4, ty + 0.45, label, color=color, dashed=dashed)
    for node in nodes[:15]:
        x, y = positions[node]
        ns = summary.nodes[node]
        body = f"{ns.function_count} funcs"
        if ns.functions:
            body += " / " + ", ".join(ns.functions[:2])
        diagram_shapes += _ppt_rect(x, y, 2.75, 0.85, node, body, "FFFFFF", "475569")
    slide2 = _slide_xml(diagram_shapes)

    _next_shape_id = 600
    slide3 = _slide_xml(
        _ppt_text(0.7, 0.55, 11.0, 0.55, "Presentation asset pack", size=2300, bold=True)
        + _ppt_rect(0.9, 1.45, 10.5, 0.7, "PowerPoint", "relationship_deck.pptx: native rectangles/connectors, editable after opening", "EFF6FF", "2563EB")
        + _ppt_rect(0.9, 2.35, 10.5, 0.7, "SVG", "file_relationships.svg: insert directly into PowerPoint or export as figure", "F0FDF4", "16A34A")
        + _ppt_rect(0.9, 3.25, 10.5, 0.7, "Mermaid", "file_relationships.mmd: useful for Markdown / GitHub / documentation", "FAF5FF", "9333EA")
        + _ppt_rect(0.9, 4.15, 10.5, 0.7, "GIF / Storyboard", "motion_storyboard.html + SVG frames; optional relationship_motion.gif when Pillow exists", "FFF7ED", "EA580C")
    )
    return [slide1, slide2, slide3]


def export_pptx(map_dir: Path, out_path: Path) -> Path:
    summary = load_project_summary(map_dir)
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    slides = _deck_slides(summary)
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("[Content_Types].xml", _content_types(len(slides)))
        zf.writestr("_rels/.rels", _root_rels())
        zf.writestr("ppt/presentation.xml", _presentation_xml(len(slides)))
        zf.writestr("ppt/_rels/presentation.xml.rels", _presentation_rels(len(slides)))
        for i, slide in enumerate(slides, start=1):
            zf.writestr(f"ppt/slides/slide{i}.xml", slide)
            zf.writestr(
                f"ppt/slides/_rels/slide{i}.xml.rels",
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"/>',
            )
    return out_path


